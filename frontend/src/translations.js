// Fonctions utilitaires de traduction
export const getTranslation = (lang) => translations[lang] || translations.fr;

export const translateBinLabel = (label, lang) => {
  if (!label) return label;
  if (lang === 'fr') return label;

  // Imbalance / XPM
  if (label.includes("Sévèrement Dominé") || label.includes("Faible (< 550)")) return "Heavily Outmatched (< 550)";
  if (label.includes("Défavorable") || label.includes("Moyen (550-650)")) return "Disadvantaged (550-650)";
  if (label.includes("Équilibré") && (label.includes("650") || label.includes("750"))) return "Balanced (650-750)";
  if (label.includes("Dominateur") || label.includes("Très Élevé (> 750)")) return "Dominant (> 750)";

  // Tilt / Streaks
  if (label.includes("Serein (Tilt 0)")) return "Calm (Tilt 0)";
  if (label.includes("Légèrement Frustré (0-1)")) return "Slightly Frustrated (0-1)";
  if (label.includes("Enervé (1-3)")) return "Tilted (1-3)";
  if (label.includes("Tilt Extrême (3+)")) return "Extreme Tilt (3+)";

  // Anciens buckets streaks
  if (label.includes("Série Victoires")) return "Win Streak (W >= 2)";
  if (label.includes("Neutre")) return "Neutral (W1 / L1)";
  if (label.includes("Défaites Légères")) return "Light Defeats (L 2-3)";
  if (label.includes("Défaites Lourdes")) return "Heavy Defeats (L 4+)";

  // Sessions
  if (label.includes("partie")) {
    return label.replace("parties", "games").replace("partie", "game");
  }

  return label;
};

export const translatePlayerCount = (count, lang) => {
  return lang === 'en' ? `${count} players` : `${count} joueurs`;
};

export const translateFeatureKey = (feature, lang) => {
  const dict = translations[lang]?.features || translations.fr.features;
  return dict[feature] || feature;
};

export const translateRankTier = (rankTier, lang) => {
  if (!rankTier) return lang === 'en' ? 'Unknown' : 'Inconnu';
  const ranksKey = ['Herald', 'Guardian', 'Crusader', 'Archon', 'Legend', 'Ancient', 'Divine', 'Immortal'];
  const rankIndex = Math.floor(rankTier / 10) - 1;
  const stars = rankTier % 10;
  
  if (rankIndex >= 7) return lang === 'en' ? 'Immortal' : 'Immortel';
  if (rankIndex >= 0 && rankIndex < ranksKey.length) {
    const key = ranksKey[rankIndex];
    const name = translations[lang]?.ranks[key] || key;
    return `${name} ${stars}`;
  }
  return lang === 'en' ? 'Unranked' : 'Sans Rang';
};
